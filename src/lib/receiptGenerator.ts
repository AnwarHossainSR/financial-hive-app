import { format } from "date-fns";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export const generateTransactionReceipt = (
  transaction: any,
  bookName: string = "Personal Finance",
  userName: string = "User"
) => {
  const doc = new jsPDF({
    unit: "mm",
    format: [80, 150], // POS thermal paper size (80mm width)
  });

  const width = doc.internal.pageSize.getWidth();
  let y = 10;

  // Header
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("FINANCIAL HIVE", width / 2, y, { align: "center" });
  y += 6;

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(bookName.toUpperCase(), width / 2, y, { align: "center" });
  y += 5;

  // Divider line
  doc.setLineDashPattern([1, 1], 0);
  doc.line(5, y, width - 5, y);
  y += 6;

  // Receipt Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("TRANSACTION RECEIPT", width / 2, y, { align: "center" });
  y += 8;

  // Details
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");

  const drawRow = (label: string, value: string) => {
    doc.setFont("helvetica", "bold");
    doc.text(label, 10, y);
    doc.setFont("helvetica", "normal");
    doc.text(value, width - 10, y, { align: "right" });
    y += 6;
  };

  const dateStr = format(new Date(transaction.date), "dd MMM yyyy, hh:mm a");
  drawRow("DATE:", dateStr);
  drawRow("TYPE:", transaction.type.toUpperCase());
  drawRow("CATEGORY:", transaction.category);

  if (transaction.note) {
    doc.setFont("helvetica", "bold");
    doc.text("NOTE:", 10, y);
    y += 5;
    doc.setFont("helvetica", "normal");
    const splitNote = doc.splitTextToSize(transaction.note, width - 20);
    doc.text(splitNote, 10, y);
    y += splitNote.length * 5;
  }

  y += 2;
  doc.line(5, y, width - 5, y);
  y += 8;

  // Amount
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("TOTAL AMOUNT", 10, y);
  y += 7;
  doc.setFontSize(16);
  const amountStr = `BDT ${Number(transaction.amount).toLocaleString(
    undefined,
    { minimumFractionDigits: 2 }
  )}`;
  doc.text(amountStr, width - 10, y, { align: "right" });
  y += 10;

  // Footer
  doc.setLineDashPattern([1, 1], 0);
  doc.line(5, y, width - 5, y);
  y += 8;

  doc.setFontSize(8);
  doc.setFont("helvetica", "italic");
  doc.text("Issued by: " + userName, width / 2, y, { align: "center" });
  y += 4;
  doc.text("Thank you for using Financial Hive", width / 2, y, {
    align: "center",
  });

  // Save the PDF
  const filename = `receipt-${transaction.id.substring(0, 8)}.pdf`;
  doc.save(filename);
};

export const generateStatementReceipt = (
  transactions: any[],
  title: string,
  stats: { income: number; expense: number; count: number },
  userName: string = "User"
) => {
  const doc = new jsPDF(); // Standard A4 for statements
  const width = doc.internal.pageSize.getWidth();
  let y = 20;

  // POS style header on A4
  doc.setFont("helvetica", "bold");
  doc.setFontSize(24);
  doc.setTextColor(59, 130, 246); // Blue-500
  doc.text("FINANCIAL HIVE", 20, y);

  doc.setFontSize(12);
  doc.setTextColor(100);
  doc.text("TRANSACTION STATEMENT", 20, y + 8);

  doc.setFontSize(10);
  doc.setTextColor(0);
  doc.text(`Generated by: ${userName}`, width - 20, y, { align: "right" });
  doc.text(`Date: ${format(new Date(), "dd MMM yyyy")}`, width - 20, y + 5, {
    align: "right",
  });

  y += 25;

  // Stats Box
  doc.setFillColor(245, 247, 250);
  doc.roundedRect(20, y, width - 40, 30, 3, 3, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text("SUMMARY", 30, y + 10);

  doc.setFont("helvetica", "normal");
  doc.text(`Total Income: BDT ${stats.income.toLocaleString()}`, 30, y + 18);
  doc.text(
    `Total Expense: BDT ${stats.expense.toLocaleString()}`,
    width / 2,
    y + 18
  );
  doc.text(
    `Net Balance: BDT ${(stats.income - stats.expense).toLocaleString()}`,
    30,
    y + 24
  );
  doc.text(`Transactions: ${stats.count}`, width / 2, y + 24);

  y += 40;

  // Table
  autoTable(doc, {
    startY: y,
    head: [["Date", "Category", "Type", "Note", "Amount"]],
    body: transactions.map((t) => [
      format(new Date(t.date), "dd/MM/yy"),
      t.category,
      t.type.toUpperCase(),
      t.note || "-",
      {
        content: `BDT ${Number(t.amount).toLocaleString()}`,
        styles: {
          fontStyle: "bold",
          textColor: t.type === "income" ? [16, 185, 129] : [239, 68, 68],
        },
      },
    ]),
    theme: "striped",
    headStyles: { fillColor: [59, 130, 246] },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    margin: { left: 20, right: 20 },
  });

  doc.save(`${title.replace(/\s+/g, "-").toLowerCase()}.pdf`);
};
